export function bd09McToBd09(x,y){
 if(!Number.isFinite(x)||!Number.isFinite(y)||Math.abs(x)>20037727||Math.abs(y)>12900000)
  throw Error('百度墨卡托坐标超出支持范围。');
 const [dx,k,...poly]=INVERSE[BANDS.findIndex(b=>Math.abs(y)>=b)];
 const t=Math.abs(y)/poly.pop();
 const lng=Math.sign(x)*(dx+k*Math.abs(x));
 const lat=Math.sign(y)*poly.reduceRight((value,coeff)=>value*t+coeff,0);
 if(!Number.isFinite(lat)||!Number.isFinite(lng)||Math.abs(lat)>76||Math.abs(lng)>180)
  throw Error('百度墨卡托坐标无效。');
 return {lat,lng};
}
