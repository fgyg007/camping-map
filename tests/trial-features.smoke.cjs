const assert=require('node:assert/strict');
const {readFile}=require('node:fs/promises');
const origin='http://127.0.0.1:5179';
module.exports=async function trialFeatures(browser,device){
 const context=await browser.newContext({...device,acceptDownloads:true});
 const errors=[];
 try{
  await context.route('**/*',route=>route.request().url().startsWith(origin+'/')?route.continue():route.abort());
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin);
  await page.getByRole('button',{name:'我的车辆'}).click();
  const vehicle=page.getByRole('dialog',{name:'我的车辆'});
  const catalog=vehicle.getByLabel('选择常见车型');
  await catalog.selectOption('li-l6-2024');
  assert.equal(await vehicle.getByLabel('车长（毫米）').inputValue(),'4925');
  assert.equal(await vehicle.getByLabel('车宽（毫米）').inputValue(),'1960');
  assert.equal(await vehicle.getByLabel('车高（毫米）').inputValue(),'1735');
  assert.match(await vehicle.getByRole('link',{name:'查看厂商资料'}).getAttribute('href'),/^https:\/\/ir\.lixiang\.com\//);
  await vehicle.getByLabel('车高（毫米）').fill('1900');
  await vehicle.getByRole('button',{name:'保存车辆'}).click();
  await vehicle.waitFor({state:'hidden'});
  await page.reload();
  await page.getByRole('button',{name:'我的车辆'}).click();
  assert.equal(await vehicle.getByLabel('车高（毫米）').inputValue(),'1900');
  await catalog.selectOption('');
  await vehicle.getByLabel('车型名称').fill('合成自改车型');
  await vehicle.getByLabel('车高（毫米）').fill('2250');
  await vehicle.getByRole('button',{name:'保存车辆'}).click();
  await vehicle.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'添加地点',exact:true}).first().click();
  await page.getByText('从地图链接导入',{exact:true}).click();
  const link=page.getByLabel('地图分享链接');
  const preview=page.getByRole('button',{name:'预览链接坐标'});
  await link.fill('https://www.google.com/maps/@39,116,16z');
  await preview.click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByLabel('纬度',{exact:true}).inputValue(),'');
  await link.fill('https://www.google.com/maps/search/?api=1&query=-33.2,151.1');
  await preview.click();
  await page.getByText(/来源：Google/).waitFor();
  await page.getByRole('button',{name:'填入表单'}).click();
  assert.equal(await page.getByLabel('纬度',{exact:true}).inputValue(),'-33.2');
  await link.fill('https://api.map.baidu.com/marker?location=39,116&coord_type=wgs84');
  await preview.click();
  await page.getByText(/来源：百度/).waitFor();
  await page.getByRole('button',{name:'填入表单'}).click();
  assert.equal(await page.getByLabel('纬度',{exact:true}).inputValue(),'39');
  assert.equal(await page.getByLabel('经度',{exact:true}).inputValue(),'116');
  await page.getByLabel('地点名称').fill('合成营地相册');
  const png=await page.evaluate(()=>{
   const c=document.createElement('canvas');c.width=96;c.height=72;
   const x=c.getContext('2d');x.fillStyle='#275a45';x.fillRect(0,0,96,72);
   x.fillStyle='#e8d9b8';x.fillRect(20,12,60,45);
   return c.toDataURL('image/png').split(',')[1];
  });
  await page.getByLabel('添加营地照片').setInputFiles({name:'synthetic.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
  await page.getByAltText('待保存照片 1',{exact:true}).waitFor();
  await page.getByRole('button',{name:'保存地点'}).click();
  const card=page.locator('.cards').getByText('合成营地相册',{exact:true});
  await card.waitFor();
  await page.reload();
  await card.click();
  await page.getByAltText('营地照片 1',{exact:true}).waitFor();
  assert.equal(await page.getByAltText('营地照片 1',{exact:true}).evaluate(img=>img.complete&&img.naturalWidth>0),true);
  await page.getByRole('button',{name:'查看营地照片 1'}).click();
  await page.getByAltText('放大营地照片 1').waitFor();
  await page.getByRole('button',{name:'关闭大图'}).click();
  assert.match(await page.getByRole('link',{name:'百度地图看点'}).getAttribute('href'),/^https:\/\/api\.map\.baidu\.com\/marker/);
  await page.getByRole('button',{name:'关闭详情'}).click();
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出备份'}).click();
  const download=await pending;
  const bytes=await readFile(await download.path());
  const backup=JSON.parse(bytes);
  assert.equal(backup.version,1);
  assert.equal(backup.vehicle.model,'合成自改车型');assert.equal(backup.vehicle.heightMm,2250);
  const only=backup.places.find(x=>x.name==='合成营地相册');
  assert.equal(only.photos.length,1);assert.match(only.photos[0],/^data:image\/jpeg;base64,/);
  const restoreContext=await browser.newContext(device);
  try{
   await restoreContext.route('**/*',route=>route.request().url().startsWith(origin+'/')?route.continue():route.abort());
   const restore=await restoreContext.newPage();
   restore.on('pageerror',e=>errors.push(e.message));
   await restore.goto(origin);
   await restore.locator('.panel-footer input[type=file]').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:bytes});
   await restore.getByRole('status').filter({hasText:'已恢复车辆'}).waitFor();
   await restore.reload();
   await restore.locator('.cards').getByText('合成营地相册',{exact:true}).click();
   await restore.getByAltText('营地照片 1',{exact:true}).waitFor();
   await restore.getByRole('button',{name:'编辑',exact:true}).click();
   await restore.getByRole('button',{name:'移除照片 1'}).click();
   await restore.getByRole('button',{name:'保存地点'}).click();
   await restore.locator('.cards').getByText('合成营地相册',{exact:true}).click();
   assert.equal(await restore.getByAltText('营地照片 1',{exact:true}).count(),0);
  }finally{await restoreContext.close();}
  assert.deepEqual(errors,[]);
  console.log('Trial features: vehicle preset/custom persistence, coordinate-only map links, JPEG photo save/view/remove, backup/restore.');
 }finally{await context.close();}
};
